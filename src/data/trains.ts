export interface Station {
  name: string;
  code: string;
  km: number;
  type: 'major' | 'regular' | 'halt';
  platformInfo?: string;
}

export interface TrainStop {
  stationCode: string;
  scheduledArrival: string;
  scheduledDeparture: string;
  expectedArrival?: string;
  expectedDeparture?: string;
  platform: string;
  status: 'passed' | 'current' | 'upcoming' | 'terminus';
  halted?: boolean;
}

export interface Train {
  number: string;
  name: string;
  type:
    | 'FAST EMU'
    | 'SLOW LOCAL'
    | 'ARAKKONAM LOCAL'
    | 'EXPRESS EMU';

  from: string;
  fromCode: string;
  to: string;
  toCode: string;

  departure: string;
  arrival: string;
  duration: string;
  platform: string;

  status:
    | 'on-time'
    | 'delayed'
    | 'cancelled'
    | 'regulated';

  delayMinutes: number;

  expectedDeparture?: string;
  expectedArrival?: string;

  stops: TrainStop[];

  currentStation?: string;
  nextStation?: string;
  runningStatus?: string;

  coaches: number;
  stopCount: number;

  delayReason?: string;
  delayReasonType?: 'confirmed' | 'estimated' | 'unavailable';
}

